# -*- coding: utf-8 -*-
"""The evidence bundle.

The assignment is explicit: *"The evidence bundle must be generated by the
implementation. Hardcoded evidence will not be accepted."*

So this module has one rule, and it is structural rather than a promise: it
reads the artifacts the run produced from **disk** and derives every verdict
from what it finds there. It is not passed the run's in-memory state and cannot
be. If a ledger is corrupted after the run and before this executes, the bundle
flips to FAIL -- which is what ``test_evidence_reflects_artifacts`` checks by
doing exactly that.

Nine rows, matching the table on the course page, each carrying a pointer to the
file and record that supports it.
"""
from __future__ import annotations

import os

from .hashing import read_json, read_jsonl, read_text, write_json, write_text
from .ledger.consumption import verify_integrity

ROWS = [
    ("tokenizer_integrity", "Tokenizer integrity", "Manifest record"),
    ("evaluation_firewall", "Evaluation firewall", "Blocked-shard event"),
    ("packing_correctness", "Packing correctness", "Packed-batch report"),
    ("mixture_compliance", "Mixture compliance", "Planned versus actual shares"),
    ("opus_audit_trail", "OPUS audit trail", "Candidate decision records"),
    ("crash_recovery", "Crash recovery", "Expected and resumed batch ids"),
    ("replay", "Replay", "Original and replay hashes"),
    ("learning_trace", "Learning trace", "Loss linked to source data"),
    ("throughput", "Throughput", "Performance report"),
]


def _safe(fn, default=None):
    try:
        return fn()
    except Exception:
        return default


def build(out_dir: str) -> dict:
    """Read the artifact directory and derive every verdict from it."""
    p = lambda *a: os.path.join(out_dir, *a)          # noqa: E731

    run_log = _safe(lambda: read_text(p("run.log")), "") or ""
    events = _safe(lambda: read_jsonl(p("events.jsonl")), []) or []
    reports = _safe(lambda: read_json(p("reports.json")), {}) or {}
    perf = _safe(lambda: read_json(p("performance.json")), {}) or {}
    cons = _safe(lambda: read_jsonl(p("ledgers", "consumption.jsonl"),
                                    tolerate_torn_tail=True), []) or []
    learn_steps = _safe(lambda: read_json(p("ledgers", "learning_steps.json")), []) or []
    learn_shards = _safe(lambda: read_json(p("ledgers", "learning_shards.json")), []) or []
    tokens = _safe(lambda: read_jsonl(p("ledgers", "learning_tokens.jsonl")), []) or []
    opus = _safe(lambda: read_jsonl(p("ledgers", "opus_decisions.jsonl")), []) or []
    firewall = _safe(lambda: read_json(p("ledgers", "firewall.json")), {}) or {}
    replay = _safe(lambda: read_json(p("ledgers", "replay.json")), {}) or {}
    resume = _safe(lambda: read_json(p("ledgers", "resume.json")), {}) or {}
    ckpts = _safe(lambda: sorted(os.listdir(p("checkpoints"))), []) or []
    manifests = _safe(lambda: sorted(os.listdir(p("manifests"))), []) or []

    checks: list[dict] = []

    def add(key: str, label: str, ev_label: str, passed: bool, detail: dict,
            path: str, pointer: str) -> None:
        checks.append({
            "requirement": label, "key": key,
            "result": "PASS" if passed else "FAIL",
            "evidence_label": ev_label, "evidence_path": path,
            "evidence_pointer": pointer, "detail": detail,
        })

    # 1 -- tokenizer integrity ------------------------------------------
    tok = reports.get("tokenizer", {})
    # index.json and mixture_schedule.json live in the same directory but are
    # not shard manifests; reading them as such added a spurious `None` to the
    # hash set and failed a check that was actually passing.
    _not_manifests = {"index.json", "mixture_schedule.json"}
    shard_manifests = [read_json(p("manifests", m)) for m in manifests
                       if m.endswith(".json") and m not in _not_manifests]
    shard_manifests = [m for m in shard_manifests if "shard_id" in m]
    hashes = {m.get("tokenizer_hash") for m in shard_manifests}
    ok = bool(tok.get("tokenizer_hash")) and hashes == {tok.get("tokenizer_hash")} \
        and "[PASS] tokenizer_hash_verified" in run_log
    add("tokenizer_integrity", "Tokenizer integrity", "Manifest record", ok,
        {"tokenizer_hash": tok.get("tokenizer_hash"),
         "vocab_size": tok.get("vocab_size"),
         "distinct_hashes_across_manifests": len(hashes),
         "manifests_checked": len(shard_manifests)},
        "manifests/", "every manifest's tokenizer_hash field")

    # 2 -- evaluation firewall -------------------------------------------
    reg = firewall.get("registry", {})
    blocked = firewall.get("blocked_probe", {})
    leaked = firewall.get("leak_scan", {})
    ok = (reg.get("registered", 0) > 0
          and blocked.get("blocked") is True
          and leaked.get("heldout_docs_in_batches", 1) == 0
          and reg.get("gradient_bearing_reads", 1) == 0
          and "[PASS] eval_shard_blocked" in run_log)
    add("evaluation_firewall", "Evaluation firewall", "Blocked-shard event", ok,
        {"registered_heldout": reg.get("registered"),
         "blocked_on_probe": blocked.get("blocked"),
         "block_reasons": blocked.get("reasons"),
         "heldout_docs_found_in_training_batches": leaked.get("heldout_docs_in_batches"),
         "validation_reads": reg.get("reads_by_split", {}).get("validation"),
         "gradient_bearing_reads": reg.get("gradient_bearing_reads")},
        "ledgers/firewall.json", "blocked_probe and leak_scan")

    # 3 -- packing correctness -------------------------------------------
    pack = perf.get("packing_by_lane", {})
    structure_ok = firewall.get("structure_preserving_no_merge", True)
    covered = all(
        r.get("coverage", 0) >= 0.85
        for lane in pack.values()
        for name, r in lane.get("by_policy", {}).items()
        if name in ("concat_chop", "greedy", "best_fit", "structure_preserving"))
    ok = bool(pack) and covered and structure_ok
    add("packing_correctness", "Packing correctness", "Packed-batch report", ok,
        {"lanes_reported": len(pack),
         "all_policies_cover_85pct_of_input": covered,
         "structure_preserving_never_merged_two_documents": structure_ok,
         "policies": sorted({name for lane in pack.values()
                             for name in lane.get("by_policy", {})})},
        "performance.json", "packing_by_lane")

    # 4 -- mixture compliance --------------------------------------------
    mc = perf.get("mixture_compliance", {})
    floors = reports.get("floors", {})
    ok = bool(mc) and mc.get("within_tolerance") is True and floors.get("floors_held") is True
    add("mixture_compliance", "Mixture compliance", "Planned versus actual shares", ok,
        {"max_abs_drift": mc.get("max_abs_drift"), "tolerance": mc.get("tolerance"),
         "protected_floors_held": floors.get("floors_held"),
         "floor_violations": floors.get("violation_count"),
         "worst_observed_share": floors.get("worst_observed_share")},
        "performance.json", "mixture_compliance + reports.json floors")

    # 5 -- OPUS audit trail ----------------------------------------------
    statuses = {d.get("status") for d in opus}
    reasons = {d.get("rejection_reason") for d in opus if d.get("rejection_reason")}
    scored = all(isinstance(d.get("opus_score"), (int, float)) for d in opus) if opus else False
    ok = (len(opus) > 0 and scored
          and {"accepted"} <= statuses
          and len(statuses) >= 3
          and all(d.get("proxy_version") and d.get("scoring_checkpoint") for d in opus))
    add("opus_audit_trail", "OPUS audit trail", "Candidate decision records", ok,
        {"decisions": len(opus), "statuses_seen": sorted(s for s in statuses if s),
         "rejection_reasons_seen": sorted(reasons),
         "every_decision_scored": scored,
         "protected_overrides": sum(1 for d in opus
                                    if d.get("protected_floor_override"))},
        "ledgers/opus_decisions.jsonl", "one record per candidate")

    # 6 -- crash recovery -------------------------------------------------
    integ = verify_integrity(cons, branch_id="main")
    ok = (resume.get("matched") is True and integ["ok"]
          and resume.get("records_discarded", -1) >= 0
          and "[PASS] resume_next_batch_matched" in run_log)
    add("crash_recovery", "Crash recovery", "Expected and resumed batch ids", ok,
        {"expected_batch_id": resume.get("expected_batch_id"),
         "actual_batch_id": resume.get("actual_batch_id"),
         "matched": resume.get("matched"),
         "records_discarded_on_rewind": resume.get("records_discarded"),
         "no_skipped_steps": integ["no_skipped_steps"],
         "no_repeated_batches": integ["no_repeated_batches"],
         "offsets_dense": integ["offsets_dense"],
         "integrity_problems": integ["problems"]},
        "ledgers/resume.json", "expected vs actual batch id + ledger integrity")

    # 7 -- replay ---------------------------------------------------------
    ok = (replay.get("all_matched") is True and replay.get("steps_compared", 0) > 0
          and "[PASS] replay_hash_matched" in run_log)
    add("replay", "Replay", "Original and replay hashes", ok,
        {"range": replay.get("range"), "steps_compared": replay.get("steps_compared"),
         "matched": replay.get("matched"),
         "compared_fields": replay.get("compared_fields"),
         "mismatches": len(replay.get("mismatches", []))},
        "ledgers/replay.json", "per-step hash comparison rows")

    # 8 -- learning trace -------------------------------------------------
    linked = sum(1 for t in tokens[:2000]
                 if t.get("shard_id") and t.get("shard_id") != "?" and t.get("doc_id"))
    sample = tokens[:2000]
    # Two fields the assignment names by name were present in the schema and null
    # in every row: gradient_alignment and loss_delta_before_after_exposure. A
    # declared-but-empty field is not evidence, so the row now requires both to
    # be populated for at least some shard. Neither can be true of every shard --
    # alignment exists only where OPUS scored, and a delta needs two probe
    # evaluations bracketing the exposure -- so the bar is "computed", not "total".
    aligned = sum(1 for r in learn_shards if r.get("gradient_alignment") is not None)
    delta_n = sum(1 for r in learn_shards
                  if r.get("loss_delta_before_after_exposure") is not None)
    ok = (len(tokens) > 0 and len(learn_shards) > 0
          and linked >= 0.95 * max(1, len(sample))
          and aligned > 0 and delta_n > 0
          and all("cross_entropy" in t and "perplexity" in t for t in sample))
    add("learning_trace", "Learning trace", "Loss linked to source data", ok,
        {"token_records": len(tokens),
         "shard_report_rows": len(learn_shards),
         "steps_recorded": len(learn_steps),
         "tokens_linked_to_shard_and_doc": f"{linked}/{len(sample)} sampled",
         "shards_with_gradient_alignment": f"{aligned}/{len(learn_shards)}",
         "shards_with_exposure_loss_delta": f"{delta_n}/{len(learn_shards)}",
         "usefulness_classes": sorted({r.get("usefulness") for r in learn_shards}),
         "eos_tracked": any(t.get("is_eos_boundary") for t in sample)},
        "ledgers/learning_tokens.jsonl", "per-token records with shard_id + doc_id")

    # 9 -- throughput ------------------------------------------------------
    rates = perf.get("rates", {})
    counters = perf.get("raw_counters", {})
    recomputable = False
    if counters and perf.get("train_seconds"):
        want = counters.get("tokens_loss_bearing", 0) / perf["train_seconds"]
        got = rates.get("useful_loss_bearing_tokens_per_second", -1)
        recomputable = abs(want - got) < max(0.01, 0.001 * max(want, 1))
    ok = bool(rates) and recomputable and bool(perf.get("formulas"))
    add("throughput", "Throughput", "Performance report", ok,
        {"useful_loss_bearing_tokens_per_second":
            rates.get("useful_loss_bearing_tokens_per_second"),
         "raw_tokens_per_second": rates.get("raw_tokens_per_second"),
         "packing_utilization": perf.get("efficiency", {}).get("packing_utilization"),
         "cache_hit_rate": perf.get("loader", {}).get("cache", {}).get("hit_rate"),
         "rate_recomputed_from_raw_counters": recomputable,
         "formulas_published": bool(perf.get("formulas"))},
        "performance.json", "rates + raw_counters + formulas")

    passed = sum(1 for c in checks if c["result"] == "PASS")
    bundle = {
        "generated_by": "tdes/evidence.py",
        "generation_method": ("read from submission_artifacts/ on disk; no value "
                              "in this bundle is taken from the run's in-memory "
                              "state, so corrupting an artifact flips its row"),
        "artifacts_read": {
            "run.log": len(run_log.splitlines()),
            "events.jsonl": len(events),
            "consumption.jsonl": len(cons),
            "learning_tokens.jsonl": len(tokens),
            "opus_decisions.jsonl": len(opus),
            "manifests": len(manifests),
            "checkpoints": len(ckpts),
        },
        "summary": {"total": len(checks), "passed": passed,
                    "failed": len(checks) - passed,
                    "all_passed": passed == len(checks)},
        "checks": checks,
    }
    return bundle


def write(out_dir: str, bundle: dict) -> dict:
    write_json(os.path.join(out_dir, "evidence.json"), bundle)
    write_text(os.path.join(out_dir, "evidence.md"), render_md(bundle))
    return bundle


def render_md(bundle: dict) -> str:
    s = bundle["summary"]
    lines = [
        "# Evidence",
        "",
        f"**{s['passed']}/{s['total']} requirements passed.**",
        "",
        "Generated by `tdes/evidence.py`, which reads `submission_artifacts/` from",
        "disk. No value below comes from the run's in-memory state -- corrupt an",
        "artifact and its row flips to FAIL (see `tests/test_evidence.py`).",
        "",
        "| Requirement | Result | Evidence |",
        "|---|---|---|",
    ]
    for c in bundle["checks"]:
        lines.append(f"| {c['requirement']} | **{c['result']}** | "
                     f"`{c['evidence_path']}` — {c['evidence_label']} |")
    lines += ["", "## Detail", ""]
    for c in bundle["checks"]:
        lines.append(f"### {c['requirement']} — {c['result']}")
        lines.append("")
        lines.append(f"Evidence: `{c['evidence_path']}` ({c['evidence_pointer']})")
        lines.append("")
        for k, v in c["detail"].items():
            lines.append(f"- `{k}`: {v}")
        lines.append("")
    lines += ["## Artifacts read", ""]
    for k, v in bundle["artifacts_read"].items():
        lines.append(f"- `{k}`: {v}")
    lines.append("")
    return "\n".join(lines)
